    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
    String keyword = txtSearch.getText().trim();

    if (keyword.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter a Student ID, name, course, or contact number.",
            "Search",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String sql = "SELECT * FROM Students WHERE "
            + "StudentID LIKE ? OR "
            + "FirstName LIKE ? OR "
            + "MiddleInitial LIKE ? OR "
            + "LastName LIKE ? OR "
            + "Course LIKE ? OR "
            + "YearLevel LIKE ? OR "
            + "Contact LIKE ?";

    DefaultTableModel model =
            (DefaultTableModel) tblStudents.getModel();

    model.setRowCount(0);

    try (Connection conn = connectDatabase()) {

        if (conn == null) {
            return;
        }

        try (PreparedStatement ps = conn.prepareStatement(sql)) {

            String searchValue = "%" + keyword + "%";

            for (int i = 1; i <= 7; i++) {
                ps.setString(i, searchValue);
            }

            try (ResultSet rs = ps.executeQuery()) {

                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getString("StudentID"),
                        rs.getString("FirstName"),
                        rs.getString("MiddleInitial"),
                        rs.getString("LastName"),
                        rs.getString("Course"),
                        rs.getString("YearLevel"),
                        rs.getString("Contact")
                    });
                }
            }
        }

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(
                this,
                "No matching student found.",
                "Search Results",
                JOptionPane.INFORMATION_MESSAGE
            );
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Search failed:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnSearchActionPerformed
