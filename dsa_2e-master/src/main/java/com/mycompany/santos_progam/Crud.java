private void setupInputRestrictions() {

    // FIRST NAME - capitalize first letter
    txtFirstName.addFocusListener(new java.awt.event.FocusAdapter() {
        @Override
        public void focusLost(java.awt.event.FocusEvent e) {
            String text = txtFirstName.getText().trim();

            if (!text.isEmpty() && !text.equals("Enter First Name")) {
                txtFirstName.setText(
                    text.substring(0, 1).toUpperCase() + text.substring(1)
                );
            }
        }
    });

    // MIDDLE INITIAL - capitalize first letter
    txtMiddleInitial.addFocusListener(new java.awt.event.FocusAdapter() {
        @Override
        public void focusLost(java.awt.event.FocusEvent e) {
            String text = txtMiddleInitial.getText().trim();

            if (!text.isEmpty() && !text.equals("Enter Middle Initial")) {
                txtMiddleInitial.setText(
                    text.substring(0, 1).toUpperCase() + text.substring(1)
                );
            }
        }
    });

    // LAST NAME - capitalize first letter
    txtLastName.addFocusListener(new java.awt.event.FocusAdapter() {
        @Override
        public void focusLost(java.awt.event.FocusEvent e) {
            String text = txtLastName.getText().trim();

            if (!text.isEmpty() && !text.equals("Enter Last Name")) {
                txtLastName.setText(
                    text.substring(0, 1).toUpperCase() + text.substring(1)
                );
            }
        }
    });

    // CONTACT - numbers only, maximum 11 digits
    txtContact.addKeyListener(new java.awt.event.KeyAdapter() {
        @Override
        public void keyTyped(java.awt.event.KeyEvent e) {
            char c = e.getKeyChar();

            if (!Character.isDigit(c) || txtContact.getText().length() >= 11) {
                e.consume();
            }
        }
    });
}
