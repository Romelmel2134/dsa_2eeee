private void loadStudents() {
    DefaultTableModel model =
            (DefaultTableModel) tblStudents.getModel();

    model.setRowCount(0);

    String sql = "SELECT * FROM Students";

    try (Connection conn = connectDatabase()) {
        if (conn == null) {
            return;
        }

        try (PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("StudentID"),
                    rs.getString("FirstName"),
                    rs.getString("MiddleInitial"),
                    rs.getString("LastName"),
                    rs.getString("Course"),
                    rs.getString("YearLevel"),
                    rs.getString("Contact")
                });
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Could not load students:\n" + e.getMessage()
        );
    }
}

private int getNextStudentId() {
    int nextID = 1;

    String sql = "SELECT MAX(CAST(StudentID AS INTEGER)) "
            + "FROM Students";

    try (Connection conn = connectDatabase()) {
        if (conn == null) {
            return -1;
        }

        try (PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            if (rs.next()) {
                nextID = rs.getInt(1) + 1;
            }
        }

        return nextID;

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Could not generate Student ID:\n" + e.getMessage()
        );
        return -1;
    }
}

