if (!contact.matches("09\\d{9}")) {
    JOptionPane.showMessageDialog(
        this,
        "Enter a valid Philippine mobile number (09XXXXXXXXX).",
        "Invalid Contact",
        JOptionPane.WARNING_MESSAGE
    );
    return;
}

if (!firstName.matches("[\\p{L}][\\p{L} '-]*")
        || !lastName.matches("[\\p{L}][\\p{L} '-]*")) {

    JOptionPane.showMessageDialog(
        this,
        "First name and last name must contain valid letters.",
        "Invalid Name",
        JOptionPane.WARNING_MESSAGE
    );
    return;
}


if (!middleInitial.matches("[\\p{L}]+([ '-][\\p{L}]+)*")) {
    JOptionPane.showMessageDialog(
        this,
        "Enter a valid middle name using letters only.",
        "Invalid Middle Name",
        JOptionPane.WARNING_MESSAGE
    );
    return;
}



int nextID = getNextStudentId();

if (nextID == -1) {
    return;
}

String studentId = String.format("%06d", nextID);

String sql = "INSERT INTO Students "
        + "(StudentID, FirstName, MiddleInitial, LastName, Course, YearLevel, Contact) "
        + "VALUES (?, ?, ?, ?, ?, ?, ?)";

try (Connection conn = connectDatabase()) {
    if (conn == null) {
        return;
    }

    try (PreparedStatement ps = conn.prepareStatement(sql)) {
        ps.setString(1, studentId);
        ps.setString(2, firstName);
        ps.setString(3, middleInitial);
        ps.setString(4, lastName);
        ps.setString(5, course);
        ps.setString(6, yearLevel);
        ps.setString(7, contact);

        ps.executeUpdate();
    }

    loadStudents();

    JOptionPane.showMessageDialog(
        this,
        "Student saved to the database successfully!",
        "Success",
        JOptionPane.INFORMATION_MESSAGE
    );

    clearFields();

} catch (SQLException e) {
    JOptionPane.showMessageDialog(
        this,
        "Could not save student:\n" + e.getMessage(),
        "Database Error",
        JOptionPane.ERROR_MESSAGE
    );
}

