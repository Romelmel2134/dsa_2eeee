    private void btnCheckoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCheckoutActionPerformed

        String paymentText = txtPayment.getText().trim();

        if (paymentText.isEmpty()) {
            lblChange.setText("Enter payment amount");
            return;
        }

        try {
            payment = Double.parseDouble(paymentText);

            if (payment < subtotal) {
                lblChange.setText("Insufficient payment");
            } else {
                change = payment - subtotal;

                lblChange.setText(
                    String.format("Change: ₱%.2f", change)
                );
            }

        } catch (NumberFormatException e) {
            lblChange.setText("Enter numbers only");
        }

    }//GEN-LAST:event_btnCheckoutActionPerformed

