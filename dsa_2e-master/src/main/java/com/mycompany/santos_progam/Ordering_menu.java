     private void updateOrderTable() {

        javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblOrder.getModel();

        model.setRowCount(0);
        
        subtotal = 0.00;

    if (burgerQty > 0) {
        double total = burgerQty * burgerPrice;

        model.addRow(new Object[]{
            "Burger",
            burgerQty,
            total
        });

        subtotal += total;
    }

    if (chickenQty > 0) {
        double total = chickenQty * chickenPrice;

        model.addRow(new Object[]{
            "Chicken",
            chickenQty,
            total
        });

        subtotal += total;
    }

    if (friesQty > 0) {
        double total = friesQty * friesPrice;

        model.addRow(new Object[]{
            "Fries",
            friesQty,
            total
        });

        subtotal += total;
    }

    if (drinkQty > 0) {
        double total = drinkQty * drinkPrice;

        model.addRow(new Object[]{
            "Soft Drink",
            drinkQty,
            total
        });

        subtotal += total;
    }

    lblSubtotal.setText(
        String.format("Subtotal: ₱%.2f", subtotal)
    );
    }
